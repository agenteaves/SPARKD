-- SPARKD Meme of the Week: equal-chance random draw protocol.
-- The production schema and lifecycle function are installed through Supabase migrations.
--
-- Rules:
-- * Every eligible submission receives one equal chance.
-- * Eligibility requires burn_verified=true and status<>'rejected'.
-- * A cryptographic shuffle selects up to three distinct finalists, then assigns podium order.
-- * pgcrypto gen_random_bytes supplies the random material.
-- * meme_week_draw_audits records entrant commitment, seed, finalists, placements, timestamp, and algorithm.
-- * meme_week_winners stores selection_method='random_equal_chance' and the draw metadata.
-- * Contest ID uniqueness makes finalization idempotent; existing winner records are never rerolled.
-- * Zero entries: no prize. One entry: first place. Two entries: first and second. Three or more: all podium places.
-- * The payout queue uses $25, $10, and $5 worth of SOL for the podium.
--
-- This file documents the production protocol. Supabase migration history remains the source of truth for DDL.
